package com.wildalert.useraccount.session

import com.wildalert.useraccount.hunter.InboundAddresses
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import java.time.Instant
import java.util.UUID

/**
 * Pure unit tests for the token mechanics — no Spring, no database.
 *
 * The session round-trip (open, resolve, close, expire) is covered in SessionIntegrationTest
 * against real Postgres, because what is worth proving there is that a row behaves correctly,
 * and a mocked repository would only prove that the mock was called.
 */
class SessionServiceTest {

    @Test
    fun `a token is 256 bits of randomness, not a readable identifier`() {
        val token = SessionService.newToken()

        // 32 bytes, base64url, unpadded.
        assertThat(token).hasSize(43)
        assertThat(token).matches("^[A-Za-z0-9_-]+$")
    }

    @Test
    fun `tokens do not repeat`() {
        // Not a probabilistic hope: at 256 bits a collision in a thousand draws would mean the
        // generator is broken, which is exactly what this would catch.
        val tokens = (1..1000).map { SessionService.newToken() }

        assertThat(tokens.distinct()).hasSameSizeAs(tokens)
    }

    @Test
    fun `a session token has far more entropy than an inbound-address token`() {
        // Both are generated by this codebase and it would be easy to reach for the existing
        // helper. InboundAddresses.newToken() is 12 characters of a 32-character alphabet (~60
        // bits), which is right for something a hunter reads off a screen and types into a camera
        // and wrong for a bearer credential. This pins the distinction deliberately.
        assertThat(SessionService.newToken().length)
            .isGreaterThan(InboundAddresses.newToken().length * 3)
    }

    @Test
    fun `expiry is inclusive, so a session does not outlive its own instant`() {
        val now = Instant.parse("2026-10-30T12:00:00Z")
        fun sessionExpiringAt(at: Instant) =
            HunterSession(tokenHash = "x".repeat(64), hunterId = UUID.randomUUID(), expiresAt = at)

        assertThat(sessionExpiringAt(now.plusSeconds(1)).isExpired(now)).isFalse()
        assertThat(sessionExpiringAt(now).isExpired(now)).isTrue()
        assertThat(sessionExpiringAt(now.minusSeconds(1)).isExpired(now)).isTrue()
    }

    @Test
    fun `the stored hash is not the token`() {
        val token = SessionService.newToken()

        val hash = SessionService.hash(token)

        // The whole point of hashing: reading the table hands over nothing usable.
        assertThat(hash).isNotEqualTo(token)
        assertThat(hash).doesNotContain(token)
    }

    @Test
    fun `hashing is SHA-256 hex, so it fits the char(64) primary key`() {
        val hash = SessionService.hash("any-token")

        assertThat(hash).hasSize(64)
        assertThat(hash).matches("^[0-9a-f]{64}$")
    }

    @Test
    fun `hashing is deterministic, which is what makes a lookup possible`() {
        // Unlike a password hash, this must be salt-free: we look a session up *by* its token.
        assertThat(SessionService.hash("same-token")).isEqualTo(SessionService.hash("same-token"))
    }

    @Test
    fun `different tokens hash differently`() {
        assertThat(SessionService.hash("token-a")).isNotEqualTo(SessionService.hash("token-b"))
    }

    @Test
    fun `a known vector, so a refactor cannot quietly change the algorithm`() {
        // SHA-256 of the ASCII string "abc". If someone swaps the digest, every live session is
        // invalidated at deploy -- a mass logout nobody intended. This catches it at build time.
        assertThat(SessionService.hash("abc"))
            .isEqualTo("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
    }
}
